from __future__ import annotations
from dataclasses import dataclass, KW_ONLY
from jaxtyping import PyTree
import jax
import jax.numpy as jnp
from jax.tree_util import register_pytree_node_class
import equinox as eqx
from ..utils import filter_tree_map, where, isfinite, LogArray, PsiArray


@dataclass
class Samples:
    r"""
    The samples generated by the sampler, with 5 attributes. Only ``spins`` is
    positional, the other attributes are keyword-only, e.g.
    ``Samples(spins, psi=psi, prob=prob)``.

    This class is mutable and not a PyTree, so it can't be passed to jitted
    functions. The attributes missing in the samples are filled in place by the
    functions computing them, e.g. `~quantax.operator.Operator.Oloc`.

    .. warning::

        A filled ``psi`` belongs to the state it was evaluated by. To reuse the
        samples with another state, or after the parameters of the state are
        updated, set ``psi`` to ``None`` or to the new wave function first.

    spins:
        The spin configurations :math:`s`.

    psi:
        The wave function :math:`\psi(s)` of the spin configurations. ``None`` if not
        evaluated yet, e.g. when the wave function evaluated by the sampler is not
        consistent with the forward pass of the state, see
        `~quantax.sampler.Sampler.sweep`.

    prob:
        The probability :math:`q_s` from which the samples are drawn, up to a
        normalization constant. It is the probability actually used by the sampler,
        e.g. :math:`|\psi(s)|^n` with the reweight factor n and :math:`\psi`
        evaluated by the sampling forward pass.
        ``None`` defaults to :math:`q_s = |\psi(s)|^2`.

    state_internal:
        The internal status of samples for the forward pass with reference.
        See `~quantax.nn.RefModel` for details.

    r:
        The reweighting factor. According to

        .. math::

            \left< x \right>_p = \frac{\sum_s p_s x_s}{\sum_s p_s}
            = \frac{\sum_s q_s x_s p_s/q_s}{\sum_s q_s p_s/q_s}
            = \frac{\left< x p/q \right>_q}{\left< p/q \right>_q},

        the expectation value with probability distribution p can be computed from
        samples with a different probability distribution q.

        The reweighting factor is defined as

        .. math::
            r_s = \frac{p_s/q_s}{\left< p/q \right>_q},

        so that :math:`\left< x \right>_p = \left< r x \right>_q`.

        Usually, :math:`p_s = |\psi(s)|^2` is the target probability,
        and :math:`q_s` can be chosen as :math:`|\psi(s)|^n` or computed from a
        helper neural network. In the former case,
        :math:`r_s = \frac{|\psi_s|^{2-n}}{\left< |\psi|^{2-n} \right>}`.
        ``None`` stands for the trivial factor :math:`r_s = 1`. If ``prob`` is given,
        ``r`` is computed from ``psi`` and ``prob`` by `update_r`.
    """

    spins: jax.Array
    _: KW_ONLY
    psi: PsiArray | None = None
    prob: PsiArray | None = None
    state_internal: PyTree = None
    r: jax.Array | None = None

    @property
    def nsamples(self) -> int:
        """Number of samples"""
        return self.spins.shape[0]

    def __getitem__(self, idx) -> Samples:
        """Index every array leaf along the leading (sample) axis, e.g. ``samples[:10]``."""
        f = lambda x: x[idx]
        fields = (self.spins, self.psi, self.prob, self.state_internal, self.r)
        spins, psi, prob, state_internal, r = filter_tree_map(f, fields)
        if r is not None:
            r = r / r.mean()
        return Samples(spins, psi=psi, prob=prob, state_internal=state_internal, r=r)

    def update_r(self) -> None:
        r"""
        Update the reweighting factor ``r`` in place from the wave function and
        probability of the samples as

        .. math::
            r_s = \frac{p_s/q_s}{\left< p/q \right>_q},
            \quad p_s = |\psi(s)|^2, \quad q_s = \text{prob}_s.

        Nothing is changed if ``prob`` is ``None``, which keeps a given ``r``.

        :raises ValueError: If ``prob`` is given but ``psi`` is ``None``.
        """
        if self.prob is None:
            return
        if self.psi is None:
            raise ValueError(
                "`psi` is required to update the reweighting factor from `prob`."
            )
        self.r = _get_r(self.psi, self.prob)

    def block_until_ready(self) -> Samples:
        """
        Wait until all arrays of the samples are computed, also called by
        `jax.block_until_ready`.
        """
        fields = (self.spins, self.psi, self.prob, self.state_internal, self.r)
        jax.block_until_ready(fields)
        return self


@eqx.filter_jit
def _get_r(psi: PsiArray, prob: PsiArray) -> jax.Array:
    # |psi|^2 / prob is computed in the LogArray representation, as |psi|^2 and prob
    # of a plain psi easily overflow or underflow. psi below single precision is
    # promoted to float32 to keep the accuracy of log|psi|.
    psi = psi.astype(jnp.promote_types(psi.dtype, jnp.float32))
    psi_abs = LogArray.from_value(abs(psi))
    r = psi_abs**2 / prob
    # Zero out non-finite weights: the normalization below would otherwise
    # spread a single bad sample over the whole array.
    r = where(isfinite(r), r, 0)
    return jnp.asarray(r / r.mean())


@register_pytree_node_class
@dataclass(frozen=True)
class SamplesTree:
    """
    An immutable PyTree of samples passed through the jitted functions of the
    Metropolis samplers, where `Samples` can't be used.
    """

    spins: jax.Array
    psi: PsiArray
    _: KW_ONLY
    state_internal: PyTree = None

    def tree_flatten(self) -> tuple[tuple, None]:
        children = (self.spins, self.psi, self.state_internal)
        aux_data = None
        return (children, aux_data)

    @classmethod
    def tree_unflatten(cls, aux_data: None, children: tuple) -> SamplesTree:
        spins, psi, state_internal = children
        return cls(spins, psi, state_internal=state_internal)
